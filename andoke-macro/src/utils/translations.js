/**
 * Función que busca la traducción correspondiente según el idioma detectado.
 * Si es español ('es') o no existe la traducción, retorna el texto original por defecto.
 */
export function translate(text, language) {
    if (language === 'es' || !translations[text]) {
        return text; // Fallback automático al texto original en Español
    }
    return translations[text][language] || text;
}